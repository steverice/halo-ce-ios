#!/usr/bin/env python3
"""Generate small synthetic C fixtures from the private Mac pipeline, without model inference or game data."""
from __future__ import annotations

import argparse
from pathlib import Path
import sys
import types

import numpy as np


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("reference", type=Path, help="directory containing upscale_lib")
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    sys.path.insert(0, str(args.reference))
    # These operations only use the model module's type aliases. Avoid loading inference dependencies.
    models = types.ModuleType("upscale_lib.models")
    models.Model = object
    models.Chain = object
    sys.modules[models.__name__] = models
    from upscale_lib import bump, consistency, damage, pipeline

    lines = ["/* Generated by tools/texture_upscale_fixtures.py from the Mac NumPy reference; synthetic data only. */"]

    def array(name, values):
        values = np.asarray(values, dtype=np.float32).ravel()
        lines.append(f"static const float {name}[] = {{")
        for start in range(0, len(values), 6):
            formatted = []
            for value in values[start:start + 6]:
                token = format(float(value), ".9g")
                if "." not in token and "e" not in token:
                    token += ".0"
                formatted.append(token + "f")
            lines.append("    " + ", ".join(formatted) + ",")
        lines.append("};")

    cases = [(16, 8, 2, True, False), (8, 4, 4, False, False), (8, 8, 8, True, True), (4, 4, 2, False, True)]
    metrics = []
    for case, (w, h, scale, wrap, transparent) in enumerate(cases):
        y, x = np.indices((h, w))
        original = np.empty((h, w, 4), np.uint8)
        for c in range(3):
            original[..., c] = (x * 37 + y * 19 + c * 53 + (x * y) % 17) % 256
        original[..., 3] = np.where((x + y) % 3 == 0, 0, 255) if transparent else 255
        if case == 3:
            original[..., 3] = 0
        yy, xx = np.indices((h * scale, w * scale))
        top = np.empty((h * scale, w * scale, 4), np.uint8)
        for c in range(3):
            base = original[yy // scale, xx // scale, c].astype(np.int32)
            top[..., c] = np.clip(base + (xx * 11 + yy * 7 + c * 17) % 91 - 45, 0, 255)
        top[..., 3] = 255
        inputs = consistency.refine_inputs(original, top, "cutout" if transparent else "color",
                                           "binary" if transparent else "none", transparent)
        mode = "wrap" if wrap else "clamp"
        metrics.append((damage.damage_share(top, inputs, "color", mode), damage.structure_loss(top, inputs, "color", mode)))
        if case == 2:
            array("pixel_expected_dilated", inputs[1])
    lines.append("static const double pixel_damage_expected[][2] = {")
    lines.extend(f"    {{ {share:.17g}, {loss:.17g} }}," for share, loss in metrics)
    lines.append("};")

    y, x, c = np.indices((4, 8, 3))
    sample = ((x * 37 + y * 19 + c * 23) % 256 / np.float32(255)).astype(np.float32)
    array("pixel_filter_input", sample)
    for wrap in (False, True):
        mode = "wrap" if wrap else "clamp"
        array(f"pixel_down_expected_{mode}", pipeline.downsample2(sample, mode=mode))
        array(f"pixel_up_expected_{mode}", consistency.upsample(sample, 2, mode=mode))

    for case, (w, h) in enumerate([(16, 8), (7, 5), (1, 7), (1, 1)]):
        y, x = np.indices((h, w))
        rgba = np.empty((h, w, 4), np.uint8)
        rgba[..., 0] = 80 + (x * 19 + y * 7) % 96
        rgba[..., 1] = 77 + (x * 11 + y * 23) % 101
        rgba[..., 2] = 205 + (x * 3 + y * 5) % 50
        rgba[..., 3] = 255
        height = bump.integrate_normals(bump.decode_normals(rgba[..., :3]))
        array(f"pixel_height_expected_{case}", height)
        array(f"pixel_normal_expected_{case}", bump.derive_normals(height * 4))

    w, h, scale = 4, 2, 8
    y, x = np.indices((h, w))
    reference = ((x * 13 + y * 29 + 63) % 128 / np.float32(255))[..., None].astype(np.float32)
    yy, xx = np.indices((h * scale, w * scale))
    top = ((xx * 11 + yy * 7 + 40) % 256 / np.float32(255))[..., None].astype(np.float32)
    projected = consistency.back_project(top, reference, scale)
    mask = consistency.damage_mask(consistency.mismatch(top, reference, scale), 12 / 255, 30 / 255)
    blended = consistency.fallback_blend(projected, reference, mask, scale)
    array("pixel_refine8_reference", reference)
    array("pixel_refine8_top", top)
    array("pixel_refine8_bp", projected)
    array("pixel_refine8_bpf", blended)
    array("pixel_refine8_mask", mask)
    bounded_cases = [(4, 2, 4, 2, False, 0.0, 1), (4, 2, 4, 4, True, 0.6, 3),
                     (1, 4, 3, 8, True, 1.4, 3), (4, 1, 4, 4, False, 1.0, 0)]
    for case, (w, h, channels, scale, wrap, sigma, iterations) in enumerate(bounded_cases):
        y, x, c = np.indices((h, w, channels))
        reference = ((x * 13 + y * 29 + c * 37 + 63) % 128 / np.float32(255)).astype(np.float32)
        yy, xx, cc = np.indices((h * scale, w * scale, channels))
        top = ((xx * 11 + yy * 7 + cc * 29 + 40) % 384 / np.float32(255)).astype(np.float32)
        mode = "wrap" if wrap else "clamp"
        projected = consistency.back_project(top, reference, scale, mode=mode, iterations=iterations)
        mask = consistency.damage_mask(consistency.mismatch(top, reference, scale, mode=mode, sigma=sigma), 12 / 255, 30 / 255)
        blended = consistency.fallback_blend(projected, reference, mask, scale, mode=mode)
        array(f"bounded_bp_{case}", projected)
        array(f"bounded_bpf_{case}", blended)
        array(f"bounded_mask_{case}", mask)
    for case, (w, h, scale) in enumerate([(4, 4, 4), (1, 4, 2), (2, 1, 8)]):
        y, x = np.indices((h, w))
        reference = (((x * 3 + y * 7) % 11).astype(np.float32) / 3 - 1.5)[..., None]
        yy, xx = np.indices((h * scale, w * scale))
        top = (((xx * 11 + yy * 7) % 63).astype(np.float32) / 9 - 3)[..., None]
        mismatch = np.abs(bump.derive_normals(consistency.down(top, scale)[..., 0])[..., :2] -
                          bump.derive_normals(reference[..., 0])[..., :2]).max(-1) / 2
        mask = consistency.damage_mask(consistency.blur(mismatch[..., None], 1)[..., 0], 12 / 255, 30 / 255)
        projected = consistency.back_project(top, reference, scale, clamp=False)
        normals = bump.derive_normals(projected[..., 0] * scale)
        target = bump.derive_normals(consistency.upsample(reference, scale)[..., 0] * scale)
        soft = np.clip(consistency.upsample(mask[..., None], scale, "mitchell"), 0, 1)
        blended = bump._renormalize(normals[..., :2] * (1 - soft) + target[..., :2] * soft)
        array(f"bounded_bump_reference_{case}", reference)
        array(f"bounded_bump_top_{case}", top)
        array(f"bounded_bump_bp_{case}", normals)
        array(f"bounded_bump_bpf_{case}", blended)
        array(f"bounded_bump_mask_{case}", mask)
    args.output.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
