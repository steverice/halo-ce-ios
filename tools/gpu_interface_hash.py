#!/usr/bin/env python3
"""Write build/ios/host/gpu_interface_hash.h: what a render capture is checked against when it is replayed.

GPU_INTERFACE_HASH is a hash of gpu.h and the headers it includes, comments and white space left out: the
layout and meaning of every call a capture holds. A capture made against another value is stale and is refused.

GPU_FRONT_END_HASH is the same of the Direct3D front end's sources, which decide what calls a frame makes. A
capture made by another front end still replays (it tests the backend against that front end's calls), with a
warning that it no longer covers what the front end does now."""
import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
INTERFACE = ("port/linux/src/gpu.h", "port/linux/src/gpu_uniforms.h", "port/linux/src/halo_stereo.h")
FRONT_END = ("port/linux/src/d3d8_device.c", "port/linux/src/d3d8_resources.c", "port/linux/src/xbox_textures.c",
             "port/linux/src/nv2a_vsh.c", "port/linux/src/nv2a_psh.c", "port/linux/src/nv2a_msl.c", "port/linux/src/xgpu.h",
             "port/linux/src/astc_rewrite.c", "port/linux/src/astc_rewrite.h",
             "port/linux/src/xgpu_text.c", "port/linux/src/hud_hires.c", "port/linux/src/text_hires.c")


def normalized(text):
    """C source without its comments and white space, so that rewording a comment or reflowing a line does not
    make every capture stale"""
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    return re.sub(r"\s+", "", text)


def source_hash(paths, root=ROOT):
    digest = hashlib.sha256()
    for path in paths:
        digest.update(path.encode() + b"\0" + normalized((root / path).read_text(errors="replace")).encode() + b"\0")
    return int.from_bytes(digest.digest()[:4], "big")


def header_text(root=ROOT):
    return ("/* generated by tools/gpu_interface_hash.py; do not edit */\n"
            f"#define GPU_INTERFACE_HASH 0x{source_hash(INTERFACE, root):08x}u\n"
            f"#define GPU_FRONT_END_HASH 0x{source_hash(FRONT_END, root):08x}u\n")


def main():
    out = ROOT / "build/ios/host/gpu_interface_hash.h"
    out.parent.mkdir(parents=True, exist_ok=True)
    text = header_text()
    if not out.exists() or out.read_text() != text:
        out.write_text(text)
    if len(sys.argv) > 1 and sys.argv[1] == "--print":
        print(text, end="")


if __name__ == "__main__":
    main()
